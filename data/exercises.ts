export type ExerciseCategory = 'quick' | 'stretch' | 'mindful' | 'active';

export interface ExerciseStep {
  id: string;
  instruction: string;
  voiceInstruction?: string; // Optional different text for voice
  duration: number; // Seconds
  animation: AnimationType;
  visualGuide: string; // Emoji
  /**
   * Per-step demo media override. Chained circuit sessions switch the GIF
   * per movement; when absent the session player falls back to the
   * exercise-level `media`.
   */
  media?: LibraryExerciseMedia;
}

export interface Exercise {
  id: string;
  title: string;
  description: string;
  category: ExerciseCategory;
  totalDuration: number; // Seconds
  color: string;
  icon: string;
  steps: ExerciseStep[];
  /**
   * Present on movement-library sessions — looping drawn demo + still pose
   * (generated by scripts/generate-move-library.mjs).
   */
  media?: LibraryExerciseMedia;
}

