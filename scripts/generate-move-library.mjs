#!/usr/bin/env node
/**
 * Move Library Generator
 *
 * Draws every desk move with the project's own figure engine (scripts/moves/:
 * rig.mjs solves and validates poses, illustrate.mjs draws the outlined
 * figure) and generates:
 *   1. assets/moves/<id>.webp        — looping animation (transparent, 320×320)
 *   2. assets/moves/<id>.still.webp  — single key pose for lists (transparent, 240×240)
 *   3. data/exerciseLibrary.generated.ts      — typed records (EN+TR names, steps, taxonomy)
 *   4. data/exerciseLibraryMedia.generated.ts — static require() map for Metro
 *
 * All artwork and text are original to this project — no third-party media.
 *
 * Usage:  npm run generate:moves
 * Check:  node scripts/moves/check.mjs   (anatomy / reach / collision rules)
 * Review: node scripts/moves/preview.mjs <out.png> [--mid] [moveId ...]
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { fitBox, sampleFrames, solveKey } from './moves/rig.mjs';
import { renderIllustrated } from './moves/illustrate.mjs';
import { checkMove } from './moves/check.mjs';
import { MOVES } from './moves/poses.mjs';
import { CATALOG } from './moves/catalog.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MEDIA_DIR = path.join(ROOT, 'assets', 'moves');
const FPS = 12;
const MOTION_SIZE = 320;
const STILL_SIZE = 240;

const BODY_PARTS = new Set(['back', 'cardio', 'chest', 'lower arms', 'lower legs', 'neck', 'shoulders', 'upper arms', 'upper legs', 'waist']);
const KINDS = new Set(['stretch', 'mobility', 'strength', 'cardio']);
const POSITIONS = new Set(['desk', 'standing']);

function validate() {
  const errors = [];
  const seen = new Set();
  for (const entry of CATALOG) {
    if (seen.has(entry.id)) errors.push(`duplicate id ${entry.id}`);
    seen.add(entry.id);
    if (!/^[a-z0-9-]+$/.test(entry.id)) errors.push(`bad id ${entry.id}`);
    if (!MOVES[entry.id]) errors.push(`no poses for ${entry.id}`);
    if (!BODY_PARTS.has(entry.bodyPart)) errors.push(`${entry.id}: bad bodyPart ${entry.bodyPart}`);
    if (!KINDS.has(entry.kind)) errors.push(`${entry.id}: bad kind ${entry.kind}`);
    if (!POSITIONS.has(entry.position)) errors.push(`${entry.id}: bad position ${entry.position}`);
    if (![1, 2, 3].includes(entry.difficulty)) errors.push(`${entry.id}: bad difficulty`);
    for (const locale of ['en', 'tr']) {
      if (!entry.name?.[locale]) errors.push(`${entry.id}: missing ${locale} name`);
      if (!entry.steps?.[locale]?.length) errors.push(`${entry.id}: missing ${locale} steps`);
    }
    if (entry.steps.en.length !== entry.steps.tr.length) errors.push(`${entry.id}: EN/TR step counts differ`);
  }
  for (const id of Object.keys(MOVES)) if (!seen.has(id)) errors.push(`poses without catalog entry: ${id}`);
  // Engine rules: every frame must pass anatomy, reach and collision checks.
  for (const entry of CATALOG) if (MOVES[entry.id]) errors.push(...checkMove(entry.id));
  return errors;
}

async function rasterize(svg, size) {
  return sharp(Buffer.from(svg), { density: 72 * (size / 512) * 2 })
    .resize(size, size)
    .png()
    .toBuffer();
}

async function buildMedia(entry) {
  const move = MOVES[entry.id];
  const frames = sampleFrames(move.keys, FPS);
  const box = fitBox(frames.map((f) => f.frame));
  const pngs = [];
  for (let i = 0; i < frames.length; i++) {
    pngs.push(await rasterize(renderIllustrated(frames[i].frame, { box, glowId: 'g' }), MOTION_SIZE));
  }
  const motionPath = path.join(MEDIA_DIR, `${entry.id}.webp`);
  await sharp(pngs, { join: { animated: true } })
    .webp({ loop: 0, delay: frames.map((f) => f.ms), quality: 78, alphaQuality: 80, effort: 6, minSize: true, mixed: true })
    .toFile(motionPath);

  const stillFrame = solveKey(move.keys[move.still ?? 0].pose);
  const stillPath = path.join(MEDIA_DIR, `${entry.id}.still.webp`);
  await sharp(await rasterize(renderIllustrated(stillFrame, { box, glowId: 'g' }), STILL_SIZE))
    .webp({ quality: 85, alphaQuality: 90, effort: 6 })
    .toFile(stillPath);

  return fs.statSync(motionPath).size + fs.statSync(stillPath).size;
}

const ts = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

function writeData(records) {
  const header = `/**
 * AUTO-GENERATED by scripts/generate-move-library.mjs — do not edit.
 * Regenerate with: npm run generate:moves
 *
 * Desk moves, illustrations and text are original to this project.
 */
`;
  const body = records
    .map((r) => `  {
    id: ${ts(`lib-${r.id}`)},
    mediaKey: ${ts(r.id)},
    name: { en: ${ts(r.name.en)}, tr: ${ts(r.name.tr)} },
    bodyPart: ${ts(r.bodyPart)},
    target: ${ts(r.target)},
    secondaryMuscles: [${r.secondary.map(ts).join(', ')}],
    kind: ${ts(r.kind)},
    position: ${ts(r.position)},
    difficulty: ${r.difficulty},
    steps: {
      en: [
        ${r.steps.en.map(ts).join(',\n        ')},
      ],
      tr: [
        ${r.steps.tr.map(ts).join(',\n        ')},
      ],
    },
  },`)
    .join('\n');
  fs.writeFileSync(
    path.join(ROOT, 'data', 'exerciseLibrary.generated.ts'),
    `${header}
import type { LibraryExerciseRecord } from '@/features/exercise-library/types';

export const LIBRARY_EXERCISES: readonly LibraryExerciseRecord[] = [
${body}
] as const;
`
  );

  const media = records
    .map((r) => `  ${ts(r.id)}: {
    animation: require('../assets/moves/${r.id}.webp'),
    still: require('../assets/moves/${r.id}.still.webp'),
  },`)
    .join('\n');
  fs.writeFileSync(
    path.join(ROOT, 'data', 'exerciseLibraryMedia.generated.ts'),
    `${header}
import type { ImageSourcePropType } from 'react-native';

export interface LibraryExerciseMedia {
  /** Looping demo (animated WebP, transparent background). */
  animation: ImageSourcePropType;
  /** Key pose for lists and cards (WebP, transparent background). */
  still: ImageSourcePropType;
}

export const LIBRARY_EXERCISE_MEDIA: Record<string, LibraryExerciseMedia> = {
${media}
};
`
  );
}

async function main() {
  const errors = validate();
  if (errors.length) {
    for (const e of errors) console.error(`✖ ${e}`);
    process.exitCode = 1;
    return;
  }
  fs.rmSync(MEDIA_DIR, { recursive: true, force: true });
  fs.mkdirSync(MEDIA_DIR, { recursive: true });

  const only = process.argv.slice(2);
  let bytes = 0;
  for (const entry of CATALOG) {
    if (only.length && !only.includes(entry.id)) continue;
    bytes += await buildMedia(entry);
  }

  // Stable order: body part, then EN name — keeps diffs reviewable.
  const records = [...CATALOG].sort(
    (a, b) => a.bodyPart.localeCompare(b.bodyPart) || a.name.en.localeCompare(b.name.en)
  );
  writeData(records);

  const counts = {};
  for (const r of records) counts[r.bodyPart] = (counts[r.bodyPart] ?? 0) + 1;
  console.log(`✔ Generated ${records.length} desk moves — media ${(bytes / 1024).toFixed(0)} KB in assets/moves/`);
  for (const [part, n] of Object.entries(counts).sort()) console.log(`  ${part}: ${n}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
